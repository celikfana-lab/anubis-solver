/* argon2_fill_fast.c — the Argon2 fill loop with a register-resident fill_block.
 *
 * A drop-in replacement for the vendored `ref.c`: core.c calls `fill_segment`,
 * and everything that is easy to get wrong (H0, H', index_alpha, the pass and
 * lane bookkeeping) still comes from the reference package. Only the 1 KiB
 * block function is different.
 *
 * Why: ref.c expands BLAKE2_ROUND_NOMSG over a block-wide array inside a
 * `for (i = 0; i < 8; ++i)` loop, so each of the 16 words a round touches is
 * indexed by the loop variable and the whole round stays in memory. Gathering a
 * round into a 16-word local with constant indices lets the compiler keep it in
 * registers; the gather and the scatter back are 32 loads and 32 stores per
 * round, against 128 of each for reading and writing the block in place.
 *
 * Measured on this machine, 19 MiB arena, pseudo-random references (us/block):
 *
 *   ref.c fill_block        2.03
 *   this file               1.73
 *
 * The Argon2id parameters Anubis uses are m=19456 KiB, t=2, p=1, which is 38912
 * blocks per hash, so 0.30 us/block is 11.8 ms/hash.
 */
#include <stdint.h>

#include "argon2.h"
#include "core.h"

#define M32 0xFFFFFFFFULL

static inline uint64_t rotr64(uint64_t x, unsigned n) {
    return (x >> n) | (x << (64 - n));
}

/* fBlaMka: x + y + 2*((x & 0xffffffff) * (y & 0xffffffff)), all mod 2^64 */
static inline uint64_t blamka(uint64_t x, uint64_t y) {
    return x + y + 2 * ((x & M32) * (y & M32));
}

#define G(a, b, c, d)                                                          \
    do {                                                                       \
        a = blamka(a, b);                                                      \
        d = rotr64(d ^ a, 32);                                                 \
        c = blamka(c, d);                                                      \
        b = rotr64(b ^ c, 24);                                                 \
        a = blamka(a, b);                                                      \
        d = rotr64(d ^ a, 16);                                                 \
        c = blamka(c, d);                                                      \
        b = rotr64(b ^ c, 63);                                                 \
    } while (0)

/* One BLAKE2 round over 16 words, exactly as BLAKE2_ROUND_NOMSG does it. The
 * land the 16 words live in does not matter; that the indices are constants
 * does. */
static inline __attribute__((always_inline)) void round16(uint64_t v[16]) {
    G(v[0], v[4], v[8], v[12]);
    G(v[1], v[5], v[9], v[13]);
    G(v[2], v[6], v[10], v[14]);
    G(v[3], v[7], v[11], v[15]);
    G(v[0], v[5], v[10], v[15]);
    G(v[1], v[6], v[11], v[12]);
    G(v[2], v[7], v[8], v[13]);
    G(v[3], v[4], v[9], v[14]);
}

/* The eight row gathers, as a constant table so the loops unroll cleanly. */
static const unsigned char ROW[16] = {0, 1, 16, 17, 32, 33, 48, 49,
                                      64, 65, 80, 81, 96, 97, 112, 113};

/* Fills a new block and optionally XORs the old one over it, as ref.c does.
 * `next` is read before it is written when with_xor is set, which is the whole
 * point of the second pass. */
static void fill_block(block *next, const block *prev, const block *ref,
                       int with_xor) {
    uint64_t r[128], t[128];
    for (int i = 0; i < 128; i++) {
        const uint64_t x = ref->v[i] ^ prev->v[i];
        r[i] = x;
        t[i] = with_xor ? (x ^ next->v[i]) : x;
    }

    /* rowwise: words 16g .. 16g+15 are contiguous */
    for (int g = 0; g < 8; g++) round16(&r[16 * g]);

    /* columnwise: (2g, 2g+1), (2g+16, 2g+17), ... (2g+112, 2g+113) */
    for (int g = 0; g < 8; g++) {
        uint64_t v[16];
        for (int j = 0; j < 16; j++) v[j] = r[2 * g + ROW[j]];
        round16(v);
        for (int j = 0; j < 16; j++) r[2 * g + ROW[j]] = v[j];
    }

    for (int i = 0; i < 128; i++) next->v[i] = t[i] ^ r[i];
}

/* Argon2i, and Argon2id in the first half of its first pass, take the reference
 * index from a block generated by the data itself rather than from memory. */
static void next_addresses(block *address_block, block *input_block,
                           const block *zero_block) {
    input_block->v[6]++;
    fill_block(address_block, zero_block, input_block, 0);
    fill_block(address_block, zero_block, address_block, 0);
}

void fill_segment(const argon2_instance_t *instance,
                  argon2_position_t position) {
    block *ref_block = NULL, *curr_block = NULL;
    block address_block, input_block, zero_block;
    uint64_t pseudo_rand, ref_index, ref_lane;
    uint32_t prev_offset, curr_offset;
    uint32_t starting_index;
    uint32_t i;
    int data_independent_addressing;

    if (instance == NULL) {
        return;
    }

    data_independent_addressing =
        (instance->type == Argon2_i) ||
        (instance->type == Argon2_id && (position.pass == 0) &&
         (position.slice < ARGON2_SYNC_POINTS / 2));

    if (data_independent_addressing) {
        init_block_value(&zero_block, 0);
        init_block_value(&input_block, 0);

        input_block.v[0] = position.pass;
        input_block.v[1] = position.lane;
        input_block.v[2] = position.slice;
        input_block.v[3] = instance->memory_blocks;
        input_block.v[4] = instance->passes;
        input_block.v[5] = instance->type;
    }

    starting_index = 0;

    if ((0 == position.pass) && (0 == position.slice)) {
        starting_index = 2; /* the first two blocks of a lane already exist */

        if (data_independent_addressing) {
            next_addresses(&address_block, &input_block, &zero_block);
        }
    }

    curr_offset = position.lane * instance->lane_length +
                  position.slice * instance->segment_length + starting_index;

    if (0 == curr_offset % instance->lane_length) {
        prev_offset = curr_offset + instance->lane_length - 1;
    } else {
        prev_offset = curr_offset - 1;
    }

    for (i = starting_index; i < instance->segment_length;
         ++i, ++curr_offset, ++prev_offset) {
        if (curr_offset % instance->lane_length == 1) {
            prev_offset = curr_offset - 1;
        }

        if (data_independent_addressing) {
            if (i % ARGON2_ADDRESSES_IN_BLOCK == 0) {
                next_addresses(&address_block, &input_block, &zero_block);
            }
            pseudo_rand = address_block.v[i % ARGON2_ADDRESSES_IN_BLOCK];
        } else {
            pseudo_rand = instance->memory[prev_offset].v[0];
        }

        ref_lane = ((pseudo_rand >> 32)) % instance->lanes;

        if ((position.pass == 0) && (position.slice == 0)) {
            ref_lane = position.lane;
        }

        position.index = i;
        ref_index = index_alpha(instance, &position, pseudo_rand & 0xFFFFFFFF,
                                ref_lane == position.lane);

        ref_block = instance->memory + instance->lane_length * ref_lane +
                    ref_index;
        curr_block = instance->memory + curr_offset;
        fill_block(curr_block, instance->memory + prev_offset, ref_block,
                   (position.pass != 0) &&
                       (instance->version != ARGON2_VERSION_10));
    }
}
