#!/usr/bin/env python3
"""
Generate arm/sve2.s: a vector-length-agnostic SVE2 SHA-256 compression kernel.

    long sha256_sve2_width(void);
    void sha256_compress_sve2(const uint32_t mid[8], const uint8_t tails[][64],
                              uint8_t out[][32]);

`width` is the number of 32-bit lanes the CPU's SVE implementation has
(svcntw(): 4 on a 128-bit machine such as Neoverse N2, 8 on 256-bit, 16 on
512-bit). This kernel differs from arm/neon.s on purpose: neon.s uses the
ARMv8 SHA-2 crypto extension to fold *one* block with sha256h, while this one
has no crypto-extension equivalent for N independent blocks, so it vectorizes
N candidate messages instead — lane i of every z register is candidate i.

Why it exists despite that (see docs/development.md): every CPU with SVE2 also
has FEAT_SHA256, and the 60-cycle crypto path beats this one. It is the batch
path for cores where FEAT_SHA2 is missing but SVE2 is present, and it is the
kernel the arm64 CI job uses to prove the SVE2 code path really executes.

Register plan (per lane = one candidate nonce):
    z0..z7    working state a..h
    z8..z23   rolling 16-word message schedule W[t%16], callee-saved
    z24..z27  scratch (sigma/sum rotations, Ch, Maj)
    z29       K[t] broadcast
    z31       gather/scatter index vector
    p0        all 32-bit lanes

Layout: tails[i*64] is candidate i's padded block, out[i*32] its digest.
Both are reached with SVE gather/scatter through an index vector
index = 4*w + 16*i words, so no explicit transpose is needed and the same
code works at any vector length.
"""

from pathlib import Path

HEADER = """\
/*
 * sve2.s — vector-length-agnostic SVE2 SHA-256 compression kernel.
 *
 * Generated by tools/gen_sve2_s.py (checked in for review); the instruction
 * sequences are hand-written, not emitted by a C compiler.
 *
 *   long sha256_sve2_width(void);
 *   void sha256_compress_sve2(const uint32_t mid[8], const uint8_t tails[][64],
 *                             uint8_t out[][32]);
 *
 * Lane i hashes tails[i*64] from the midstate mid[]; every lane shares the
 * same midstate. out[i*32] receives the big-endian digest. The number of
 * lanes is whatever SVC (4/8/16); see sha256_sve2_width().
 *
 * The schedule is kept in registers and the rounds rotate register names at
 * generation time, so no register copies are needed for a..h.
 */

    .arch armv8.5-a+sve2
"""

K = [
    0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
    0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
    0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
    0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
    0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
    0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
    0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
    0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
]

ST = ["z%d" % i for i in range(8)]           # a..h
W = ["z%d" % i for i in range(8, 24)]        # 16 schedule words
ACC, R1, R2, MISC = "z24", "z25", "z26", "z27"
KV, IDX = "z29", "z31"

P = ".s"          # element type
PRED = "p0/m"


def ror(dst, src, n):
    """dst = ror(src, n) in two instructions (lsr then insert)."""
    return [
        "    lsr     %s%s, %s%s, #%d" % (dst, P, src, P, n),
        "    sli     %s%s, %s%s, #%d" % (dst, P, src, P, 32 - n),
    ]


def add3(dst, a, b):
    """dst += a + b, destructive on dst (predicated add)."""
    return ["    add     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, a, P),
            "    add     %s%s, %s%s, %s%s" % (dst, P, dst, P, b, P)]


def eor3(dst, a, b):
    return ["    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, a, P),
            "    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, b, P)]


def big_sigma1(dst, x):
    """Sigma1(x) = ror6 ^ ror11 ^ ror25."""
    out = ["    // Sigma1(%s)" % x]
    out += ror(dst, x, 6)
    out += ror(R1, x, 11)
    out += ror(R2, x, 25)
    out += ["    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, R1, P),
            "    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, R2, P)]
    return out


def big_sigma0(dst, x):
    """Sigma0(x) = ror2 ^ ror13 ^ ror22."""
    out = ["    // Sigma0(%s)" % x]
    out += ror(dst, x, 2)
    out += ror(R1, x, 13)
    out += ror(R2, x, 22)
    out += ["    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, R1, P),
            "    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, R2, P)]
    return out


def small_sigma0(dst, x):
    """sigma0(x) = ror7 ^ ror18 ^ (x >> 3)."""
    out = ["    // sigma0(%s)" % x]
    out += ror(dst, x, 7)
    out += ror(R1, x, 18)
    out += ["    lsr     %s%s, %s%s, #3" % (R2, P, x, P)]
    out += ["    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, R1, P),
            "    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, R2, P)]
    return out


def small_sigma1(dst, x):
    """sigma1(x) = ror17 ^ ror19 ^ (x >> 10)."""
    out = ["    // sigma1(%s)" % x]
    out += ror(dst, x, 17)
    out += ror(R1, x, 19)
    out += ["    lsr     %s%s, %s%s, #10" % (R2, P, x, P)]
    out += ["    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, R1, P),
            "    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, R2, P)]
    return out


def ch(dst, e, f, g):
    """Ch(e,f,g) = (e & f) ^ (~e & g), rewritten as ((f ^ g) & e) ^ g."""
    return [
        "    // Ch(%s,%s,%s)" % (e, f, g),
        "    mov     %s%s, %s, %s%s" % (dst, P, PRED, f, P),
        "    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, g, P),
        "    and     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, e, P),
        "    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, g, P),
    ]


def maj(dst, tmp, a, b, c):
    """Maj(a,b,c) = (a & b) ^ ((a ^ b) & c)."""
    return [
        "    // Maj(%s,%s,%s)" % (a, b, c),
        "    mov     %s%s, %s, %s%s" % (dst, P, PRED, a, P),
        "    and     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, b, P),
        "    mov     %s%s, %s, %s%s" % (tmp, P, PRED, a, P),
        "    eor     %s%s, %s, %s%s, %s%s" % (tmp, P, PRED, tmp, P, b, P),
        "    and     %s%s, %s, %s%s, %s%s" % (tmp, P, PRED, tmp, P, c, P),
        "    eor     %s%s, %s, %s%s, %s%s" % (dst, P, PRED, dst, P, tmp, P),
    ]


def schedule_step(t):
    """W[t%16] = W[t-16] + sigma0(W[t-15]) + sigma1(W[t-2]) + W[t-7]."""
    cur = W[t % 16]
    out = ["", "    // W[%d]" % t]
    out += small_sigma0(ACC, W[(t - 15) % 16])
    out += small_sigma1(MISC, W[(t - 2) % 16])
    out += ["    add     %s%s, %s, %s%s, %s%s" % (cur, P, PRED, cur, P, ACC, P)]
    out += ["    add     %s%s, %s, %s%s, %s%s" % (cur, P, PRED, cur, P, MISC, P)]
    out += ["    add     %s%s, %s%s, %s%s" % (cur, P, cur, P, W[(t - 7) % 16], P)]
    return out


def round_step(t, a, b, c, d, e, f, g, h):
    """One SHA-256 round; the caller rotates the a..h names afterwards."""
    out = ["", "    // round %d: %s..%s" % (t, a, h)]
    out += ["    ld1rw   {%s%s}, p0/z, [x3, #%d]" % (KV, P, 4 * t)]
    out += big_sigma1(ACC, e)
    out += ch(MISC, e, f, g)
    out += ["    add     %s%s, %s, %s%s, %s%s" % (ACC, P, PRED, ACC, P, MISC, P)]
    out += ["    add     %s%s, %s, %s%s, %s%s" % (ACC, P, PRED, ACC, P, h, P)]
    out += ["    add     %s%s, %s, %s%s, %s%s" % (ACC, P, PRED, ACC, P, KV, P)]
    out += ["    add     %s%s, %s, %s%s, %s%s" % (ACC, P, PRED, ACC, P, W[t % 16], P)]
    out += big_sigma0(R1, a)
    out += maj(R2, MISC, a, b, c)
    out += ["    add     %s%s, %s, %s%s, %s%s" % (R1, P, PRED, R1, P, R2, P)]
    out += ["    // d += T1 ; the register that held h becomes the new a"]
    out += ["    add     %s%s, %s, %s%s, %s%s" % (d, P, PRED, d, P, ACC, P)]
    out += ["    add     %s%s, %s%s, %s%s" % (h, P, ACC, P, R1, P)]
    return out


def main():
    L = [HEADER, "", "    .text", "", "/* long sha256_sve2_width(void) */",
         "    .global sha256_sve2_width", "    .type sha256_sve2_width, %function",
         "sha256_sve2_width:", "    cntw    x0", "    ret",
         "    .size sha256_sve2_width, .-sha256_sve2_width", ""]
    L += ["/* void sha256_compress_sve2(const uint32_t mid[8], const uint8_t tails[][64],",
          " *                             uint8_t out[][32]); */",
          "    .global sha256_compress_sve2",
          "    .type sha256_compress_sve2, %function",
          "sha256_compress_sve2:",
          "    sub     sp, sp, #256",
          "    str     q8, [sp, #0]", "    str     q9, [sp, #16]",
          "    str     q10, [sp, #32]", "    str     q11, [sp, #48]",
          "    str     q12, [sp, #64]", "    str     q13, [sp, #80]",
          "    str     q14, [sp, #96]", "    str     q15, [sp, #112]",
          "    str     q16, [sp, #128]", "    str     q17, [sp, #144]",
          "    str     q18, [sp, #160]", "    str     q19, [sp, #176]",
          "    str     q20, [sp, #192]", "    str     q21, [sp, #208]",
          "    str     q22, [sp, #224]", "    str     q23, [sp, #240]",
          "    ptrue   p0.s",
          "    adrp    x3, .Lk", "    add     x3, x3, :lo12:.Lk",
          "", "    // midstate: one broadcast per word, same for every lane"]
    for i in range(8):
        L.append("    ld1rw   {%s%s}, p0/z, [x0, #%d]" % (ST[i], P, 4 * i))
    L += ["", "    // W[0..15]: gather word w of every candidate, then swap to host order",
          "    mov     w4, #16                 // lane stride: 64 bytes = 16 words"]
    for w in range(16):
        # index is in elements: the gather's UXTW #2 scales it by 4 bytes, so
        # word w of lane i sits at w + 16*i (64-byte lane stride).
        L.append("    mov     w3, #%d" % w)
        L.append("    index   %s%s, w3, w4" % (IDX, P))
        L.append("    ld1w    {%s%s}, p0/z, [x1, %s%s, uxtw #2]" % (W[w], P, IDX, P))
        L.append("    revb    %s%s, %s, %s%s" % (W[w], P, PRED, W[w], P))
    L += ["", "    // 64 rounds, register names rotated at generation time"]
    st = list(ST)
    for t in range(64):
        if t >= 16:
            L += schedule_step(t)
        a, b, c, d, e, f, g, h = st
        L += round_step(t, a, b, c, d, e, f, g, h)
        st = [h, a, b, c, d, e, f, g]
    L += ["", "    // add the midstate back, then write big-endian digests by scatter"]
    for i in range(8):
        L.append("    ld1rw   {%s%s}, p0/z, [x0, #%d]" % (IDX, P, 4 * i))
        L.append("    add     %s%s, %s, %s%s, %s%s" % (ST[i], P, PRED, ST[i], P, IDX, P))
        L.append("    revb    %s%s, %s, %s%s" % (ST[i], P, PRED, ST[i], P))
    L += ["    mov     w4, #8                  // out stride: 32 bytes = 8 words"]
    for i in range(8):
        L.append("    mov     w3, #%d" % i)
        L.append("    index   %s%s, w3, w4" % (IDX, P))
        L.append("    st1w    {%s%s}, p0, [x2, %s%s, uxtw #2]" % (ST[i], P, IDX, P))
    L += ["", "    ldr     q8, [sp, #0]", "    ldr     q9, [sp, #16]",
          "    ldr     q10, [sp, #32]", "    ldr     q11, [sp, #48]",
          "    ldr     q12, [sp, #64]", "    ldr     q13, [sp, #80]",
          "    ldr     q14, [sp, #96]", "    ldr     q15, [sp, #112]",
          "    ldr     q16, [sp, #128]", "    ldr     q17, [sp, #144]",
          "    ldr     q18, [sp, #160]", "    ldr     q19, [sp, #176]",
          "    ldr     q20, [sp, #192]", "    ldr     q21, [sp, #208]",
          "    ldr     q22, [sp, #224]", "    ldr     q23, [sp, #240]",
          "    add     sp, sp, #256", "    ret",
          "    .size sha256_compress_sve2, .-sha256_compress_sve2", "",
          "    .section .rodata", "    .align 4", ".Lk:"]
    for i in range(0, 64, 8):
        L.append("    .word   " + ", ".join("0x%08x" % k for k in K[i:i + 8]))
    L.append("")

    out = Path(__file__).resolve().parent.parent / "src" / "cpu" / "arm" / "sve2.s"
    out.write_text("\n".join(L))
    print("wrote", out, "(%d lines)" % len(L))


if __name__ == "__main__":
    main()
