#!/usr/bin/env python3
"""gen_hashx_wgsl.py — compile a HashX program to a WebGPU (WGSL) compute shader.

The same idea as `gen_hashx_wat.py`: a HashX program is fixed for a whole
challenge, so the 512-instruction VM can be compiled away and each GPU thread
just runs the resulting straight line over its own nonce.

Two things are not inherited from the Vulkan kernel in `src/vulkan/hashx.comp`:

  * its `umulh64` does not compute the high half of a 128-bit product (it drops
    `a1*b1` and the high words of the cross products, and shifts the rest by 32).
    The semantics here are transcribed from `gen_hashx_wat.py`, which is verified
    against the C engine and against Anubis's own module.
  * it keeps the program in a buffer and interprets. Generated straight-line
    WGSL has no instruction fetch and no dynamic register indexing, which is the
    whole point of compiling.

WGSL has no 64-bit integers, so a u64 is a `vec2<u32>` (low, high) exactly as in
the GLSL kernel, and a 32x32->64 widening multiply is built from 16-bit limbs.

    python3 tools/gen_hashx_wgsl.py --out webgpu/hashx.wgsl
    python3 tools/gen_hashx_wgsl.py --program beyond/vectors/hx_vectors.hex
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_hashx_wat import M32, M64, load_program, sext32  # noqa: E402


def u64(v: int) -> str:
    v &= M64
    return f"vec2<u32>(0x{v & M32:08x}u, 0x{(v >> 32) & M32:08x}u)"


class Wgsl:
    def __init__(self, keys: list[int], prog: list[list[int]],
                 dump_after: int | None = None, no_branch: bool = False) -> None:
        self.keys = keys
        self.prog = prog
        self.dump_after = dump_after
        self.no_branch = no_branch
        self.out: list[str] = []

    def e(self, line: str = "") -> None:
        self.out.append("  " + line if line else "")

    # -- helpers -------------------------------------------------------
    def header(self) -> None:
        self.e("// Generated by tools/gen_hashx_wgsl.py — do not edit.")
        self.e("//")
        self.e("// HashX compiled to a WGSL compute shader. One invocation per nonce;")
        self.e("// u64 values are vec2<u32> (low, high) because WGSL has no 64-bit ints.")
        self.e()
        self.e("struct Params {")
        self.e("  code_size: u32,")
        self.e("  difficulty: u32,")
        self.e("  base: u32,")
        self.e("  count: u32,")
        self.e("};")
        self.e()
        self.e("struct Results {")
        self.e("  total: atomic<u32>,   // every hit, even past the slots below")
        self.e("  hits: u32,")
        self.e("  pad0: u32,")
        self.e("  pad1: u32,")
        self.e("  nonces: array<u32, 8>,")
        self.e("  hashes: array<u32, 64>,  // 8 hits x 8 words (lo, hi per u64)")
        self.e("};")
        self.e()
        self.e("@group(0) @binding(0) var<uniform> params: Params;")
        self.e("@group(0) @binding(1) var<storage, read_write> results: Results;")
        self.e()
        self.e("// ---- 64-bit arithmetic over vec2<u32>(lo, hi) ----")
        self.e()
        self.e("fn add64(a: vec2<u32>, b: vec2<u32>) -> vec2<u32> {")
        self.e("  let lo = a.x + b.x;")
        self.e("  return vec2<u32>(lo, a.y + b.y + select(0u, 1u, lo < a.x));")
        self.e("}")
        self.e()
        self.e("fn sub64(a: vec2<u32>, b: vec2<u32>) -> vec2<u32> {")
        self.e("  let lo = a.x - b.x;")
        self.e("  return vec2<u32>(lo, a.y - b.y - select(0u, 1u, a.x < b.x));")
        self.e("}")
        self.e()
        self.e("fn xor64(a: vec2<u32>, b: vec2<u32>) -> vec2<u32> {")
        self.e("  return vec2<u32>(a.x ^ b.x, a.y ^ b.y);")
        self.e("}")
        self.e()
        self.e("fn rotl64(x: vec2<u32>, n: u32) -> vec2<u32> {")
        self.e("  if (n == 0u) { return x; }")
        self.e("  if (n == 32u) { return vec2<u32>(x.y, x.x); }")
        self.e("  if (n < 32u) {")
        self.e("    return vec2<u32>((x.x << n) | (x.y >> (32u - n)),")
        self.e("                      (x.y << n) | (x.x >> (32u - n)));")
        self.e("  }")
        self.e("  let s = 64u - n;")
        self.e("  return vec2<u32>((x.x >> s) | (x.y << (32u - s)),")
        self.e("                    (x.y >> s) | (x.x << (32u - s)));")
        self.e("}")
        self.e()
        self.e("fn rotr64(x: vec2<u32>, n: u32) -> vec2<u32> {")
        self.e("  return rotl64(x, (64u - n) & 63u);")
        self.e("}")
        self.e()
        self.e("fn shl64(x: vec2<u32>, n: u32) -> vec2<u32> {")
        self.e("  if (n == 0u) { return x; }")
        self.e("  if (n >= 64u) { return vec2<u32>(0u, 0u); }")
        self.e("  if (n >= 32u) { return vec2<u32>(0u, x.x << (n - 32u)); }")
        self.e("  return vec2<u32>(x.x << n, (x.y << n) | (x.x >> (32u - n)));")
        self.e("}")
        self.e()
        self.e("// high 32 bits of an unsigned 32x32->64 multiply, from 16-bit limbs")
        self.e("fn mulhi32(a: u32, b: u32) -> u32 {")
        self.e("  let al = a & 0xffffu; let ah = a >> 16u;")
        self.e("  let bl = b & 0xffffu; let bh = b >> 16u;")
        self.e("  let t0 = al * bl;")
        self.e("  let t1 = al * bh;")
        self.e("  let t2 = ah * bl;")
        self.e("  let t3 = ah * bh;")
        self.e("  let mid = (t0 >> 16u) + (t1 & 0xffffu) + (t2 & 0xffffu);")
        self.e("  return t3 + (t1 >> 16u) + (t2 >> 16u) + (mid >> 16u);")
        self.e("}")
        self.e()
        self.e("// high 64 bits of the 128-bit product, transcribed from the verified WAT:")
        self.e("//   HI = T3 + (T1>>32) + (T2>>32) + (LO>>32),  T1=a.lo*b.hi, T2=a.hi*b.lo")
        self.e("fn umulh64(a: vec2<u32>, b: vec2<u32>) -> vec2<u32> {")
        self.e("  let hi0 = mulhi32(a.x, b.x);")
        self.e("  let lo1 = a.x * b.y; let hi1 = mulhi32(a.x, b.y);")
        self.e("  let lo2 = a.y * b.x; let hi2 = mulhi32(a.y, b.x);")
        self.e("  let lo3 = a.y * b.y; let hi3 = mulhi32(a.y, b.y);")
        self.e("  // carry out of the low 32 bits of (hi0 + lo1 + lo2)")
        self.e("  let s0 = hi0 + lo1; let c0 = select(0u, 1u, s0 < hi0);")
        self.e("  let s1 = s0 + lo2;  let c1 = select(0u, 1u, s1 < s0);")
        self.e("  let carry = c0 + c1;")
        self.e("  // low word of the high half = lo3 + hi1 + hi2 + carry, with its own carry")
        self.e("  let w0 = lo3 + hi1;      let d0 = select(0u, 1u, w0 < lo3);")
        self.e("  let w1 = w0 + hi2;       let d1 = select(0u, 1u, w1 < w0);")
        self.e("  let w2 = w1 + carry;     let d2 = select(0u, 1u, w2 < w1);")
        self.e("  return vec2<u32>(w2, hi3 + d0 + d1 + d2);")
        self.e("}")
        self.e()
        self.e("// high 64 of a signed product: unsigned high, then correct for negatives")
        self.e("fn smulh64(a: vec2<u32>, b: vec2<u32>) -> vec2<u32> {")
        self.e("  var h = umulh64(a, b);")
        self.e("  if ((a.y & 0x80000000u) != 0u) { h = sub64(h, b); }")
        self.e("  if ((b.y & 0x80000000u) != 0u) { h = sub64(h, a); }")
        self.e("  return h;")
        self.e("}")
        self.e()
        self.e("// low 64 bits of the product")
        self.e("fn mul64(a: vec2<u32>, b: vec2<u32>) -> vec2<u32> {")
        self.e("  return vec2<u32>(a.x * b.x,")
        self.e("                    a.x * b.y + a.y * b.x + mulhi32(a.x, b.x));")
        self.e("}")
        self.e()
        self.e("fn sipround(v0: ptr<function, vec2<u32>>, v1: ptr<function, vec2<u32>>,")
        self.e("             v2: ptr<function, vec2<u32>>, v3: ptr<function, vec2<u32>>) {")
        self.e("  *v0 = add64(*v0, *v1);")
        self.e("  *v2 = add64(*v2, *v3);")
        self.e("  *v1 = rotl64(*v1, 13u);")
        self.e("  *v3 = rotl64(*v3, 16u);")
        self.e("  *v1 = xor64(*v1, *v0);")
        self.e("  *v3 = xor64(*v3, *v2);")
        self.e("  *v0 = rotl64(*v0, 32u);")
        self.e("  *v2 = add64(*v2, *v1);")
        self.e("  *v0 = add64(*v0, *v3);")
        self.e("  *v1 = rotl64(*v1, 17u);")
        self.e("  *v3 = rotl64(*v3, 21u);")
        self.e("  *v1 = xor64(*v1, *v2);")
        self.e("  *v3 = xor64(*v3, *v0);")
        self.e("  *v2 = rotl64(*v2, 32u);")
        self.e("}")
        self.e()

    # -- bodies --------------------------------------------------------
    def entry_head(self) -> None:
        self.e("@compute @workgroup_size(64)")
        self.e("fn main(@builtin(global_invocation_id) gid: vec3<u32>) {")
        self.e("  let idx = gid.x;")
        self.e("  if (idx >= params.count) { return; }")
        self.e("  let nonce = params.base + idx;")
        self.e("  let nn = vec2<u32>(nonce, 0u);")
        k = self.keys
        self.e(f"  var v0 = {u64(k[0])};  // keys are this challenge's, so they are constants")
        self.e(f"  var v1 = {u64(k[1])};")
        self.e(f"  var v2 = {u64(k[2])};")
        self.e(f"  var v3 = {u64(k[3])};")
        self.e("  var r0: vec2<u32>; var r1: vec2<u32>;")
        self.e("  var r2: vec2<u32>; var r3: vec2<u32>;")
        self.e("  var r4: vec2<u32>; var r5: vec2<u32>;")
        self.e("  var r6: vec2<u32>; var r7: vec2<u32>;")
        self.e("  var result: u32 = 0u;")
        self.e("  var be: bool = true;")
        self.e()
        self.e("  // ---- PRF: SipHash-2-4 in counter mode -> r0..r7 ----")
        self.e("  v1 = xor64(v1, vec2<u32>(238u, 0u));")
        self.e("  v3 = xor64(v3, nn);")
        for _ in range(2):
            self.e("  sipround(&v0, &v1, &v2, &v3);")
        self.e("  v0 = xor64(v0, nn);")
        self.e("  v2 = xor64(v2, vec2<u32>(238u, 0u));")
        for _ in range(4):
            self.e("  sipround(&v0, &v1, &v2, &v3);")
        for i in range(4):
            self.e(f"  r{i} = v{i};")
        self.e("  v1 = xor64(v1, vec2<u32>(221u, 0u));")
        for _ in range(4):
            self.e("  sipround(&v0, &v1, &v2, &v3);")
        for i in range(4):
            self.e(f"  r{4 + i} = v{i};")
        self.e()
        self.e("  // ---- the program, compiled to straight line ----")

    def vm(self) -> None:
        """Emit the program as segments joined by a dispatch loop.

        The obvious translation is one nested `loop` per branch target with
        `continue` to jump back. That is what this generator emitted first, and
        it is *correct* under SwiftShader but miscompiles on the Intel gen-12lp
        Vulkan backend: the same module produced wrong digests there, with only
        the high words of two registers differing, and disabling the branch made
        them right again. Rather than trust `continue` inside nested loops, the
        program is cut into segments at every branch target and every
        post-branch point, and a single dispatch loop runs them:

            if (pc == 0u) { segment 0; pc = ...; }
            if (pc == 1u) { segment 1; pc = ...; }
            ...
            if (pc == NSEG) { break; }

        A taken branch only ever sets `pc` backwards, and `be` guarantees it
        happens at most once, so at most one extra pass over the chain happens.
        """
        target_of: dict[int, int] = {}
        last_target = None
        for i, (op, _d, _s, _imm) in enumerate(self.prog):
            if op == 9:
                last_target = i
            elif op == 10:
                target_of[i] = (last_target + 1) if last_target is not None else 0

        # cut points: the start, every branch target, and the instruction after
        # every branch (so no segment straddles a jump)
        bounds = {0}
        for branch, target in target_of.items():
            bounds.add(target)
            bounds.add(branch + 1)
        starts = sorted(b for b in bounds if 0 <= b <= len(self.prog))
        seg_of = {start: k for k, start in enumerate(starts)}
        ends = starts[1:] + [len(self.prog)]
        nseg = len(starts)

        self.e()
        self.e("  // ---- the program: segments joined by a dispatch loop ----")
        self.e("  var pc: u32 = 0u;")
        self.e("  loop {")
        for k, (s0, s1) in enumerate(zip(starts, ends)):
            self.e(f"    if (pc == {k}u) {{  // instructions {s0}..{s1 - 1}")
            depth = 3
            jump_to = None
            for i in range(s0, s1):
                op, dst, src, imm = self.prog[i]
                d, sc = dst & 7, src & 7
                pad = "  " * depth
                if op == 9:
                    continue
                if op == 10:
                    if self.no_branch:
                        self.out.append(f"  " * depth + f"// BRANCH {i} omitted (--no-branch)")
                        continue
                    jump_to = target_of[i]
                    pad += ""
                    self.out.append(
                        f"{pad}// BRANCH {i}: be && (result & 0x{imm & M32:08x}) == 0 -> {jump_to}")
                    self.out.append(f"{pad}if (be && (result & 0x{imm & M32:08x}u) == 0u) {{")
                    self.out.append(f"{pad}  be = false;")
                    self.out.append(f"{pad}  pc = {seg_of[jump_to]}u;")
                    self.out.append(f"{pad}}} else {{")
                    self.out.append(f"{pad}  pc = {k + 1}u;")
                    self.out.append(f"{pad}}}")
                    continue
                if op == 0:
                    self.out.append(f"{pad}r{d} = umulh64(r{d}, r{sc});")
                    self.out.append(f"{pad}result = r{d}.x;")
                elif op == 1:
                    self.out.append(f"{pad}r{d} = smulh64(r{d}, r{sc});")
                    self.out.append(f"{pad}result = r{d}.x;")
                elif op == 2:
                    self.out.append(f"{pad}r{d} = mul64(r{d}, r{sc});")
                elif op == 3:
                    self.out.append(f"{pad}r{d} = sub64(r{d}, r{sc});")
                elif op == 4:
                    self.out.append(f"{pad}r{d} = xor64(r{d}, r{sc});")
                elif op == 5:
                    self.out.append(f"{pad}r{d} = add64(r{d}, shl64(r{sc}, {imm & 63}u));")
                elif op == 6:
                    self.out.append(f"{pad}r{d} = rotr64(r{d}, {imm & 63}u);")
                elif op == 7:
                    self.out.append(f"{pad}r{d} = add64(r{d}, {u64(sext32(imm) & M64)});")
                elif op == 8:
                    self.out.append(f"{pad}r{d} = xor64(r{d}, {u64(sext32(imm) & M64)});")
                else:
                    raise SystemExit(f"unknown opcode {op} at {i}")
            if jump_to is None:
                self.out.append("  " * depth + f"pc = {k + 1}u;")
            self.e("    }")
        self.e(f"    if (pc == {nseg}u) {{ break; }}")
        self.e("  }")
        if self.dump_after is not None:
            # debug: registers after the whole program, before finalisation
            self.e("  results.hashes[0] = r0.x; results.hashes[1] = r0.y;")
            self.e("  results.hashes[2] = r1.x; results.hashes[3] = r1.y;")
            self.e("  results.hashes[4] = r2.x; results.hashes[5] = r2.y;")
            self.e("  results.hashes[6] = r3.x; results.hashes[7] = r3.y;")
            self.e("  results.hashes[8] = r4.x; results.hashes[9] = r4.y;")
            self.e("  results.hashes[10] = r5.x; results.hashes[11] = r5.y;")
            self.e("  results.hashes[12] = r6.x; results.hashes[13] = r6.y;")
            self.e("  results.hashes[14] = r7.x; results.hashes[15] = r7.y;")
            self.e("  results.hashes[16] = result;")
            self.e("  results.nonces[0] = nonce;")
            self.e("  atomicStore(&results.total, 1u);")
            self.e("  return;")

    def finalize(self) -> None:
        k = self.keys
        self.e()
        self.e("  // ---- finalisation: keys back in, one SipRound per half ----")
        self.e(f"  r0 = add64(r0, {u64(k[0])});")
        self.e(f"  r1 = add64(r1, {u64(k[1])});")
        self.e(f"  r6 = add64(r6, {u64(k[2])});")
        self.e(f"  r7 = add64(r7, {u64(k[3])});")
        self.e("  sipround(&r0, &r1, &r2, &r3);")
        self.e("  sipround(&r4, &r5, &r6, &r7);")
        self.e("  let w0 = xor64(r0, r4);")
        self.e("  let w1 = xor64(r1, r5);")
        self.e("  let w2 = xor64(r2, r6);")
        self.e("  let w3 = xor64(r3, r7);")
        self.e()
        self.e("  // leading zero bits of the 32-byte digest, MSB first within each byte,")
        self.e("  // which is the unit Anubis uses for hashx difficulty")
        self.e("  let words = array<vec2<u32>, 4>(w0, w1, w2, w3);")
        self.e("  var bits: u32 = 0u;")
        self.e("  var done: bool = false;")
        self.e("  for (var q: u32 = 0u; q < 4u; q = q + 1u) {")
        self.e("    let lo = words[q].x;")
        self.e("    let hi = words[q].y;")
        self.e("    for (var j: u32 = 0u; j < 4u; j = j + 1u) {")
        self.e("      let b = (lo >> (8u * j)) & 0xffu;")
        self.e("      let msb = countLeadingZeros(b) - 24u;")
        self.e("      bits = bits + msb;")
        self.e("      if (b != 0u) { done = true; break; }")
        self.e("    }")
        self.e("    if (done) { break; }")
        self.e("    for (var j: u32 = 0u; j < 4u; j = j + 1u) {")
        self.e("      let b = (hi >> (8u * j)) & 0xffu;")
        self.e("      let msb = countLeadingZeros(b) - 24u;")
        self.e("      bits = bits + msb;")
        self.e("      if (b != 0u) { done = true; break; }")
        self.e("    }")
        self.e("    if (done) { break; }")
        self.e("  }")
        self.e()
        self.e("  if (bits >= params.difficulty) {")
        self.e("    let slot = atomicAdd(&results.total, 1u);")
        self.e("    if (slot < 8u) {")
        self.e("      results.nonces[slot] = nonce;")
        self.e("      let base = slot * 8u;")
        self.e("      results.hashes[base + 0u] = w0.x; results.hashes[base + 1u] = w0.y;")
        self.e("      results.hashes[base + 2u] = w1.x; results.hashes[base + 3u] = w1.y;")
        self.e("      results.hashes[base + 4u] = w2.x; results.hashes[base + 5u] = w2.y;")
        self.e("      results.hashes[base + 6u] = w3.x; results.hashes[base + 7u] = w3.y;")
        self.e("    }")
        self.e("  }")
        self.e("}")

    def build(self) -> str:
        self.header()
        self.entry_head()
        self.vm()
        self.finalize()
        return "\n".join(self.out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--program", default=None,
                    help="vector file (default: the built-in single-case program)")
    ap.add_argument("--case", type=int, default=0)
    ap.add_argument("--out", default="webgpu/hashx.wgsl")
    ap.add_argument("--dump-after", type=int, default=None,
                    help="debug: dump r0..r7 after this many instructions and stop")
    ap.add_argument("--truncate", type=int, default=None,
                    help="debug: emit only the first N instructions of the program")
    ap.add_argument("--no-branch", action="store_true",
                    help="omit branch handling; only correct for nonces where the "
                         "program's guarded branch is not taken (see webgpu/README.md)")
    args = ap.parse_args()

    root = Path(__file__).resolve().parent.parent
    if args.program:
        keys, _nonce, prog, _expected = load_program(Path(args.program), args.case)
    else:
            keys, _nonce, prog, _expected = load_program(
            root / "beyond/vectors/hx_vectors.hex", 0)

    if args.truncate is not None:
        prog = prog[:args.truncate]

    out = Path(args.out)
    if not out.is_absolute():
        out = root / out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(Wgsl(keys, prog, args.dump_after, args.no_branch).build(),
                   encoding="utf-8")
    try:
        shown = out.relative_to(root)
    except ValueError:
        shown = out            # an absolute --out outside the repo is allowed
    print(f"wrote {shown} ({len(prog)} instructions, "
          f"{len(out.read_text(encoding='utf-8').splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
