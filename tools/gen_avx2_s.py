#!/usr/bin/env python3
"""
Generate avx2.s: an 8-way AVX2 SHA-256 compression kernel.

This is our own assembly, not compiler output. The repetitive parts (48
message-schedule steps and 64 rounds with rotating register names) are expanded
here so the .s file stays reviewable and the round macro is written once.

    void sha256_compress8_avx2(const uint32_t mid[8],
                               const uint8_t tails[8][64],
                               uint8_t out[8][32]);

The eight input messages are the padded tail blocks (one 64-byte block each)
that follow a shared prefix whose midstate is `mid`. Lane i's block is at
tails[i*64]. Output lane i is the 32-byte big-endian digest at out[i*32].

Calling convention: SysV AMD64 (rdi, rsi, rdx); state in ymm0..ymm7,
temporaries in ymm8..ymm12, message schedule in a 2 KiB stack frame.
"""

from pathlib import Path

HEADER = """\
/*
 * avx2.s — 8-way AVX2 SHA-256 compression.
 *
 * Generated by gen_avx2_s.py (checked in for review); the instruction
 * sequences are written by hand, not emitted by a C compiler.
 *
 *   void sha256_compress8_avx2(const uint32_t mid[8],
 *                              const uint8_t tails[8][64],
 *                              uint8_t out[8][32]);
 *
 * Each lane hashes one padded 64-byte tail block from a shared midstate.
 * The message schedule lives in a 2 KiB stack frame; the eight SHA-256
 * state words stay in ymm0..ymm7 across all 64 rounds, with the register
 * roles rotated by the macro arguments instead of being moved.
 */

    .section .rodata
    .align 32
.Lavx2_kb:
"""

K = [
    0x428A2F98, 0x71374491, 0xB5C0FBCF, 0xE9B5DBA5, 0x3956C25B, 0x59F111F1,
    0x923F82A4, 0xAB1C5ED5, 0xD807AA98, 0x12835B01, 0x243185BE, 0x550C7DC3,
    0x72BE5D74, 0x80DEB1FE, 0x9BDC06A7, 0xC19BF174, 0xE49B69C1, 0xEFBE4786,
    0x0FC19DC6, 0x240CA1CC, 0x2DE92C6F, 0x4A7484AA, 0x5CB0A9DC, 0x76F988DA,
    0x983E5152, 0xA831C66D, 0xB00327C8, 0xBF597FC7, 0xC6E00BF3, 0xD5A79147,
    0x06CA6351, 0x14292967, 0x27B70A85, 0x2E1B2138, 0x4D2C6DFC, 0x53380D13,
    0x650A7354, 0x766A0ABB, 0x81C2C92E, 0x92722C85, 0xA2BFE8A1, 0xA81A664B,
    0xC24B8B70, 0xC76C51A3, 0xD192E819, 0xD6990624, 0xF40E3585, 0x106AA070,
    0x19A4C116, 0x1E376C08, 0x2748774C, 0x34B0BCB5, 0x391C0CB3, 0x4ED8AA4A,
    0x5B9CCA4F, 0x682E6FF3, 0x748F82EE, 0x78A5636F, 0x84C87814, 0x8CC70208,
    0x90BEFFFA, 0xA4506CEB, 0xBEF9A3F7, 0xC67178F2,
]

PROLOGUE = """
    .text
    .globl sha256_compress8_avx2
    .hidden sha256_compress8_avx2
    .type sha256_compress8_avx2, @function

/* w[i] = w[i-16] + s0(w[i-15]) + w[i-7] + s1(w[i-2]) */
.macro SCHED i
    vmovdqa (\\i-15)*32(%rsp), %ymm8
    vpsrld  $7, %ymm8, %ymm9
    vpslld  $25, %ymm8, %ymm10
    vpor    %ymm10, %ymm9, %ymm9
    vpsrld  $18, %ymm8, %ymm10
    vpslld  $14, %ymm8, %ymm11
    vpor    %ymm11, %ymm10, %ymm10
    vpxor   %ymm10, %ymm9, %ymm9
    vpsrld  $3, %ymm8, %ymm10
    vpxor   %ymm10, %ymm9, %ymm9
    vpaddd  (\\i-16)*32(%rsp), %ymm9, %ymm9
    vpaddd  (\\i-7)*32(%rsp), %ymm9, %ymm9
    vmovdqa (\\i-2)*32(%rsp), %ymm8
    vpsrld  $17, %ymm8, %ymm10
    vpslld  $15, %ymm8, %ymm11
    vpor    %ymm11, %ymm10, %ymm10
    vpsrld  $19, %ymm8, %ymm11
    vpslld  $13, %ymm8, %ymm12
    vpor    %ymm12, %ymm11, %ymm11
    vpxor   %ymm11, %ymm10, %ymm10
    vpsrld  $10, %ymm8, %ymm11
    vpxor   %ymm11, %ymm10, %ymm10
    vpaddd  %ymm10, %ymm9, %ymm9
    vmovdqa %ymm9, \\i*32(%rsp)
.endm

/* One SHA-256 round. After it, \\h holds the new a and \\d the new e, so the
 * next round's arguments are rotated right by one. */
.macro ROUND a,b,c,d,e,f,g,h,wo,ko
    vpsrld  $6, \\e, %ymm8
    vpslld  $26, \\e, %ymm9
    vpor    %ymm9, %ymm8, %ymm8
    vpsrld  $11, \\e, %ymm9
    vpslld  $21, \\e, %ymm10
    vpor    %ymm10, %ymm9, %ymm9
    vpxor   %ymm9, %ymm8, %ymm8
    vpsrld  $25, \\e, %ymm9
    vpslld  $7, \\e, %ymm10
    vpor    %ymm10, %ymm9, %ymm9
    vpxor   %ymm9, %ymm8, %ymm8

    vpxor   \\g, \\f, %ymm9
    vpand   \\e, %ymm9, %ymm9
    vpxor   \\g, %ymm9, %ymm9
    vpaddd  %ymm9, %ymm8, %ymm8
    vpaddd  .Lavx2_kb+\\ko(%rip), %ymm8, %ymm8
    vpaddd  \\wo(%rsp), %ymm8, %ymm8
    vpaddd  \\h, %ymm8, %ymm8

    vpsrld  $2, \\a, %ymm9
    vpslld  $30, \\a, %ymm10
    vpor    %ymm10, %ymm9, %ymm9
    vpsrld  $13, \\a, %ymm10
    vpslld  $19, \\a, %ymm11
    vpor    %ymm11, %ymm10, %ymm10
    vpxor   %ymm10, %ymm9, %ymm9
    vpsrld  $22, \\a, %ymm10
    vpslld  $10, \\a, %ymm11
    vpor    %ymm11, %ymm10, %ymm10
    vpxor   %ymm10, %ymm9, %ymm10

    vpand   \\b, \\a, %ymm11
    vpxor   \\b, \\a, %ymm12
    vpand   \\c, %ymm12, %ymm12
    vpxor   %ymm12, %ymm11, %ymm11
    vpaddd  %ymm11, %ymm10, %ymm9

    vpaddd  %ymm9, %ymm8, \\h
    vpaddd  %ymm8, \\d, \\d
.endm

/* Build one message word across the eight lanes. */
.macro LOADW off, woff
    movl    \\off+0(%rsi), %eax
    bswap   %eax
    vmovd   %eax, %xmm8
    movl    \\off+64(%rsi), %eax
    bswap   %eax
    vpinsrd $1, %eax, %xmm8, %xmm8
    movl    \\off+128(%rsi), %eax
    bswap   %eax
    vpinsrd $2, %eax, %xmm8, %xmm8
    movl    \\off+192(%rsi), %eax
    bswap   %eax
    vpinsrd $3, %eax, %xmm8, %xmm8
    movl    \\off+256(%rsi), %eax
    bswap   %eax
    vmovd   %eax, %xmm9
    movl    \\off+320(%rsi), %eax
    bswap   %eax
    vpinsrd $1, %eax, %xmm9, %xmm9
    movl    \\off+384(%rsi), %eax
    bswap   %eax
    vpinsrd $2, %eax, %xmm9, %xmm9
    movl    \\off+448(%rsi), %eax
    bswap   %eax
    vpinsrd $3, %eax, %xmm9, %xmm9
    vinserti128 $1, %xmm9, %ymm8, %ymm8
    vmovdqa %ymm8, \\woff(%rsp)
.endm

sha256_compress8_avx2:
    pushq   %rbp
    movq    %rsp, %rbp
    andq    $-32, %rsp
    subq    $2112, %rsp
"""


def emit_k() -> str:
    # Each constant broadcast to all eight lanes: the round add is a
    # 256-bit memory operand, so the table entry must be 8 copies of K[i].
    lines = []
    for v in K:
        lines.append("    .long " + ", ".join([f"0x{v:08x}"] * 8))
    return "\n".join(lines)


def emit_loadw() -> str:
    lines = []
    for i in range(16):
        lines.append(f"    LOADW {4 * i}, {32 * i}")
    return "\n".join(lines)


def emit_sched() -> str:
    return "\n".join(f"    SCHED {i}" for i in range(16, 64))


def emit_state_init() -> str:
    lines = []
    for i in range(8):
        lines.append(f"    vmovd   {4 * i}(%rdi), %xmm8")
        lines.append(f"    vpbroadcastd %xmm8, %ymm{i}")
    return "\n".join(lines)


def emit_rounds() -> str:
    lines = []
    for k in range(64):
        regs = [f"%ymm{((i - k) % 8)}" for i in range(8)]
        lines.append(
            f"    ROUND {','.join(regs)},{32 * k},{32 * k}"
        )
    return "\n".join(lines)


def emit_epilogue() -> str:
    out = ["""
    /* Add the prefix midstate and write the eight lane digests. */
    vmovd   0(%rdi), %xmm8
    vpbroadcastd %xmm8, %ymm8
    vpaddd  %ymm8, %ymm0, %ymm0
    vmovd   4(%rdi), %xmm8
    vpbroadcastd %xmm8, %ymm8
    vpaddd  %ymm8, %ymm1, %ymm1
    vmovd   8(%rdi), %xmm8
    vpbroadcastd %xmm8, %ymm8
    vpaddd  %ymm8, %ymm2, %ymm2
    vmovd   12(%rdi), %xmm8
    vpbroadcastd %xmm8, %ymm8
    vpaddd  %ymm8, %ymm3, %ymm3
    vmovd   16(%rdi), %xmm8
    vpbroadcastd %xmm8, %ymm8
    vpaddd  %ymm8, %ymm4, %ymm4
    vmovd   20(%rdi), %xmm8
    vpbroadcastd %xmm8, %ymm8
    vpaddd  %ymm8, %ymm5, %ymm5
    vmovd   24(%rdi), %xmm8
    vpbroadcastd %xmm8, %ymm8
    vpaddd  %ymm8, %ymm6, %ymm6
    vmovd   28(%rdi), %xmm8
    vpbroadcastd %xmm8, %ymm8
    vpaddd  %ymm8, %ymm7, %ymm7
"""]
    # spill each word vector and write big-endian dwords per lane
    for i in range(8):
        out.append(f"    vmovdqa %ymm{i}, 2048(%rsp)")
        for lane in range(8):
            out.append(f"    movl    {2048 + 4 * lane}(%rsp), %eax")
            out.append("    bswap   %eax")
            out.append(f"    movl    %eax, {32 * lane + 4 * i}(%rdx)")
    out.append("""
    movq    %rbp, %rsp
    popq    %rbp
    vzeroupper
    ret
    .size sha256_compress8_avx2, .-sha256_compress8_avx2

    .section .note.GNU-stack,"",@progbits
""")
    return "\n".join(out)


def main() -> None:
    parts = [HEADER, emit_k(), PROLOGUE, emit_loadw(), "\n    /* message schedule */",
             emit_sched(), "\n    /* initial state */", emit_state_init(),
             "\n    /* 64 rounds, register roles rotated */",
             emit_rounds(), emit_epilogue()]
    out = Path(__file__).resolve().parent.parent / "src" / "avx2.s"
    with open(out, "w") as f:
        f.write("\n".join(parts))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
